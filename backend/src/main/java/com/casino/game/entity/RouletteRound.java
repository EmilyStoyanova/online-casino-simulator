package com.casino.game.entity;

import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Objects;
import java.util.UUID;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import org.hibernate.annotations.Immutable;
import org.springframework.data.domain.Persistable;

/**
 * One played roulette round ({@code roulette_rounds}, V9), stored once, complete, in the transaction that
 * also writes its ledger entries (W4-06). Never changed afterwards: no setters, {@link Immutable}, and the
 * database rejects {@code UPDATE} and {@code DELETE} (trigger {@code trg_roulette_rounds_append_only}).
 *
 * <ul>
 *   <li>The id is generated by the caller before the ledger writes, so the ledger keys and references
 *       can name the round. {@link Persistable#isNew()} makes Spring Data insert it directly instead of
 *       looking it up first.</li>
 *   <li>The player and the ledger entries are referenced by id only (Q11): {@code user_id} →
 *       {@code users}, {@code stake_transaction_id}/{@code payout_transaction_id} →
 *       {@code wallet_transactions}, all {@code ON DELETE RESTRICT}. No JPA relationship crosses into
 *       the {@code user} or {@code wallet} module.</li>
 *   <li>{@code createdAt} comes from the caller (the injected {@code Clock} in W4-06), truncated to the
 *       microseconds that {@code timestamptz} stores, so a round read back later is equal to the one
 *       returned when it was played. ({@code @Generated} cannot be combined with {@code @Immutable} for an
 *       entity whose id is assigned: Hibernate rejects the post-insert refresh of a read-only entity.)</li>
 *   <li>The bets belong to the round (unidirectional one-to-many, inserted with it) and load in insertion
 *       order (their identity id), i.e. the order of the request.</li>
 * </ul>
 */
@Entity
@Immutable
@Table(name = "roulette_rounds")
public class RouletteRound implements Persistable<UUID> {

    @Id
    private UUID id;

    @Column(name = "user_id", nullable = false, updatable = false)
    private UUID userId;

    @Column(name = "request_id", nullable = false, updatable = false)
    private UUID requestId;

    @Column(name = "winning_number", nullable = false, updatable = false)
    private short winningNumber;

    @Column(name = "total_stake", nullable = false, updatable = false)
    private long totalStake;

    @Column(name = "total_payout", nullable = false, updatable = false)
    private long totalPayout;

    @Column(name = "balance_after", nullable = false, updatable = false)
    private long balanceAfter;

    @Column(name = "stake_transaction_id", nullable = false, updatable = false)
    private long stakeTransactionId;

    @Column(name = "payout_transaction_id", updatable = false)
    private Long payoutTransactionId;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Immutable
    @OneToMany(cascade = CascadeType.PERSIST, fetch = FetchType.LAZY)
    @JoinColumn(name = "round_id", nullable = false, updatable = false)
    @OrderBy("id")
    private List<RouletteBet> bets = new ArrayList<>();

    @Transient
    private boolean persisted;

    /** For JPA. */
    protected RouletteRound() {
    }

    /**
     * A round to be inserted with its bets.
     *
     * @param id                  round id, generated by the caller (named in the ledger keys)
     * @param userId              the player
     * @param requestId           the client's {@code Idempotency-Key}
     * @param winningNumber       0–36
     * @param totalStake          sum of the bets' amounts
     * @param totalPayout         sum of the bets' payouts
     * @param balanceAfter        the wallet balance right after the round
     * @param stakeTransactionId  the round's {@code ROULETTE_STAKE} ledger entry
     * @param payoutTransactionId its {@code ROULETTE_PAYOUT} entry, or {@code null} when nothing was won
     * @param bets                the bets in request order, at least one
     * @param createdAt           when the round was played (stored with microsecond precision)
     */
    public RouletteRound(UUID id, UUID userId, UUID requestId, int winningNumber, long totalStake, long totalPayout,
                         long balanceAfter, long stakeTransactionId, Long payoutTransactionId, List<RouletteBet> bets,
                         Instant createdAt) {
        this.id = Objects.requireNonNull(id, "id");
        this.userId = Objects.requireNonNull(userId, "userId");
        this.requestId = Objects.requireNonNull(requestId, "requestId");
        this.winningNumber = (short) winningNumber;
        this.totalStake = totalStake;
        this.totalPayout = totalPayout;
        this.balanceAfter = balanceAfter;
        this.stakeTransactionId = stakeTransactionId;
        this.payoutTransactionId = payoutTransactionId;
        Objects.requireNonNull(bets, "bets");
        if (bets.isEmpty()) {
            throw new IllegalArgumentException("A round has at least one bet");
        }
        this.bets = new ArrayList<>(bets);
        this.createdAt = Objects.requireNonNull(createdAt, "createdAt").truncatedTo(ChronoUnit.MICROS);
    }

    @Override
    public UUID getId() {
        return id;
    }

    /** {@code true} until the round has been inserted or loaded, so Spring Data persists it directly. */
    @Override
    public boolean isNew() {
        return !persisted;
    }

    @PostPersist
    @PostLoad
    void markPersisted() {
        persisted = true;
    }

    public UUID getUserId() {
        return userId;
    }

    public UUID getRequestId() {
        return requestId;
    }

    public int getWinningNumber() {
        return winningNumber;
    }

    public long getTotalStake() {
        return totalStake;
    }

    public long getTotalPayout() {
        return totalPayout;
    }

    public long getBalanceAfter() {
        return balanceAfter;
    }

    public long getStakeTransactionId() {
        return stakeTransactionId;
    }

    public Long getPayoutTransactionId() {
        return payoutTransactionId;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    /** The bets in request order; read-only. */
    public List<RouletteBet> getBets() {
        return Collections.unmodifiableList(bets);
    }
}
