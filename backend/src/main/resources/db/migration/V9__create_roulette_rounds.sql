-- Roulette rounds and their bets (docs/plans/week-04.md §5.3; decisions Q8, Q11, Q19).
--
-- A round is written once, complete, in the same transaction as its ledger entries (W4-06): there
-- is no pending state. Rows never change afterwards (append-only triggers). Category and option names
-- are those of the API contract (openapi.yaml 0.5.0) and of com.casino.game.model.
--
-- The foreign keys into wallet_transactions prove that the referenced entries exist and keep them from
-- being deleted. That an entry is the round's own stake or payout (its wallet, type, amount and
-- reference) is guaranteed by the single writer (RouletteService, W4-06) and checked by the read-only
-- reconciliation of W4-08 (docs/plans/week-04.md §5.5, §5.7).

-- Generic append-only guard for tables whose rows are final once inserted. The ledger keeps its own
-- function (reject_ledger_change, V6) unchanged.
CREATE FUNCTION reject_row_change()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS
$$
BEGIN
    RAISE EXCEPTION '% is append-only: % rejected', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

COMMENT ON FUNCTION reject_row_change() IS 'Rejects UPDATE and DELETE of append-only rows (roulette_rounds, roulette_bets).';

CREATE TABLE roulette_rounds (
    id                    UUID        PRIMARY KEY,            -- generated by the application before the ledger writes
    user_id               UUID        NOT NULL,               -- the player of the session
    request_id            UUID        NOT NULL,               -- the client's Idempotency-Key
    winning_number        SMALLINT    NOT NULL,
    total_stake           BIGINT      NOT NULL,
    total_payout          BIGINT      NOT NULL,
    balance_after         BIGINT      NOT NULL,               -- wallet balance right after the round
    stake_transaction_id  BIGINT      NOT NULL,               -- the round's ROULETTE_STAKE entry
    payout_transaction_id BIGINT,                             -- its ROULETTE_PAYOUT entry, only when something was won
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_roulette_rounds_user            FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_roulette_rounds_stake_entry     FOREIGN KEY (stake_transaction_id) REFERENCES wallet_transactions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_roulette_rounds_payout_entry    FOREIGN KEY (payout_transaction_id) REFERENCES wallet_transactions (id) ON DELETE RESTRICT,
    CONSTRAINT uq_roulette_rounds_request         UNIQUE (user_id, request_id),
    CONSTRAINT uq_roulette_rounds_stake_entry     UNIQUE (stake_transaction_id),
    CONSTRAINT uq_roulette_rounds_payout_entry    UNIQUE (payout_transaction_id),
    CONSTRAINT ck_roulette_rounds_number          CHECK (winning_number BETWEEN 0 AND 36),
    CONSTRAINT ck_roulette_rounds_stake           CHECK (total_stake BETWEEN 1 AND 9007199254740991),
    CONSTRAINT ck_roulette_rounds_payout          CHECK (total_payout BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_roulette_rounds_balance         CHECK (balance_after BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_roulette_rounds_payout_entry    CHECK ((total_payout = 0) = (payout_transaction_id IS NULL)),
    CONSTRAINT ck_roulette_rounds_distinct_entries CHECK (payout_transaction_id IS NULL OR payout_transaction_id <> stake_transaction_id)
);

CREATE TABLE roulette_bets (
    id        BIGINT      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,  -- order of the bets in the request
    round_id  UUID        NOT NULL,
    category  VARCHAR(10) NOT NULL,
    selection VARCHAR(6),                                        -- option of RED_BLACK, EVEN_ODD, LOW_HIGH, DOZEN
    number    SMALLINT,                                          -- option of STRAIGHT
    amount    BIGINT      NOT NULL,
    payout    BIGINT      NOT NULL,                              -- stake + net winnings on a win, 0 on a loss
    CONSTRAINT fk_roulette_bets_round     FOREIGN KEY (round_id) REFERENCES roulette_rounds (id) ON DELETE RESTRICT,
    CONSTRAINT uq_roulette_bets_selection UNIQUE NULLS NOT DISTINCT (round_id, category, selection, number),
    CONSTRAINT ck_roulette_bets_category  CHECK (category IN ('STRAIGHT', 'RED_BLACK', 'EVEN_ODD', 'LOW_HIGH', 'DOZEN')),
    -- Every branch tests its option with IS NOT NULL first: a CHECK passes when its expression is NULL,
    -- and "number BETWEEN 0 AND 36" or "selection IN (...)" alone would be NULL for a missing option.
    CONSTRAINT ck_roulette_bets_option    CHECK (
           (category = 'STRAIGHT'  AND selection IS NULL AND number IS NOT NULL AND number BETWEEN 0 AND 36)
        OR (category = 'RED_BLACK' AND number IS NULL AND selection IS NOT NULL AND selection IN ('RED', 'BLACK'))
        OR (category = 'EVEN_ODD'  AND number IS NULL AND selection IS NOT NULL AND selection IN ('EVEN', 'ODD'))
        OR (category = 'LOW_HIGH'  AND number IS NULL AND selection IS NOT NULL AND selection IN ('LOW', 'HIGH'))
        OR (category = 'DOZEN'     AND number IS NULL AND selection IS NOT NULL AND selection IN ('FIRST', 'SECOND', 'THIRD'))),
    CONSTRAINT ck_roulette_bets_amount    CHECK (amount BETWEEN 1 AND 9007199254740991),
    CONSTRAINT ck_roulette_bets_payout    CHECK (payout = 0 OR payout = amount * CASE category
                                                     WHEN 'STRAIGHT' THEN 36 WHEN 'DOZEN' THEN 3 ELSE 2 END)
);

CREATE TRIGGER trg_roulette_rounds_append_only BEFORE UPDATE OR DELETE ON roulette_rounds
    FOR EACH ROW EXECUTE FUNCTION reject_row_change();

CREATE TRIGGER trg_roulette_bets_append_only BEFORE UPDATE OR DELETE ON roulette_bets
    FOR EACH ROW EXECUTE FUNCTION reject_row_change();
